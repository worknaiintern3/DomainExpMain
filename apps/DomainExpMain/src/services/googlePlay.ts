import * as Linking from 'expo-linking';
import * as WebBrowser from 'expo-web-browser';
import { Platform } from 'react-native';

import { apiGet, apiPost, getEffectiveApiUrl } from './api';
import { getItem, STORAGE_KEYS } from './storage';

export interface GooglePlayStatus {
  connected: boolean;
  googleAccount?: {
    email: string;
  };
  developerAccount?: {
    id: string;
  };
}

export interface GooglePlayApp {
  packageName: string;
  appName: string;
  playStoreUrl: string;
}

export interface GooglePlayAppsResponse {
  success: boolean;
  developerAccount: {
    id: string;
  };
  googleAccount: {
    email: string;
  };
  apps: GooglePlayApp[];
}

export const PLAY_STORE_URL_REGEX =
  /^https:\/\/play\.google\.com\/store\/apps\/details\?id=([a-zA-Z][a-zA-Z0-9_]*(\.[a-zA-Z][a-zA-Z0-9_]*)+)$/;

export async function fetchGooglePlayStatus(): Promise<GooglePlayStatus> {
  return await apiGet<GooglePlayStatus>('/google-play/status');
}

export async function fetchGooglePlayApps(): Promise<GooglePlayAppsResponse> {
  return await apiGet<GooglePlayAppsResponse>('/google-play/apps');
}

export async function verifyGooglePlayDeveloperAccount(
  developerAccountId: string,
): Promise<{ verified: boolean; developerAccountId: string; googleAccountEmail: string }> {
  const cleanId = developerAccountId.trim();
  if (!cleanId) {
    throw new Error('Please enter a valid Google Play Developer Account ID.');
  }

  return await apiPost('/google-play/verify-account', {
    developerAccountId: cleanId,
  });
}

export async function refreshGooglePlayTokens(): Promise<{ success: boolean; tokenExpiresAt: string }> {
  return await apiPost('/google-play/refresh', {});
}

export async function disconnectGooglePlay(): Promise<{ success: boolean }> {
  return await apiPost('/google-play/disconnect', {});
}

export async function startGooglePlayConnectFlow(
  developerAccountId?: string,
): Promise<{ success: boolean; cancelled?: boolean; message?: string }> {
  try {
    const token = await getItem(STORAGE_KEYS.ACCESS_TOKEN);
    const baseUrl = getEffectiveApiUrl();

    // Deep link redirect for mobile app
    const deepLinkRedirect = Linking.createURL('google-play-callback');

    // Retrieve OAuth URL from backend
    const authUrlResponse = await apiGet<{ authUrl: string; state: string }>(
      `/google-play/auth?${developerAccountId ? `developerAccountId=${encodeURIComponent(developerAccountId.trim())}&` : ''}redirectUri=${encodeURIComponent(`${baseUrl}/google-play/callback`)}`,
    );

    if (!authUrlResponse || !authUrlResponse.authUrl) {
      throw new Error('Unable to start Google authorization.');
    }

    if (Platform.OS === 'web') {
      // In web browser, navigate directly or open popup
      if (typeof window !== 'undefined') {
        const popup = window.open(authUrlResponse.authUrl, '_blank', 'width=520,height=680');
        return new Promise((resolve) => {
          const interval = setInterval(async () => {
            if (popup && popup.closed) {
              clearInterval(interval);
              const status = await fetchGooglePlayStatus().catch(() => ({ connected: false }));
              resolve({ success: status.connected });
            }
          }, 1000);
        });
      }
      return { success: false, message: 'Web environment not ready' };
    }

    // React Native / Expo OAuth session
    const authResult = await WebBrowser.openAuthSessionAsync(
      authUrlResponse.authUrl,
      deepLinkRedirect,
    );

    if (authResult.type === 'cancel' || authResult.type === 'dismiss') {
      return {
        success: false,
        cancelled: true,
        message: 'Google sign-in was cancelled.',
      };
    }

    if (authResult.type === 'success') {
      const url = authResult.url;
      if (url.includes('error=')) {
        const errorParam = url.split('error=')[1]?.split('&')[0];
        const decodedError = decodeURIComponent(errorParam || 'Authentication failed');
        return {
          success: false,
          cancelled: decodedError.includes('access_denied') || decodedError.includes('cancel'),
          message: decodedError,
        };
      }

      // Check connected status
      const status = await fetchGooglePlayStatus().catch(() => ({ connected: false }));
      return { success: status.connected };
    }

    return { success: false, message: 'OAuth session did not complete.' };
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Google OAuth failed';
    return { success: false, message };
  }
}

/**
 * Validates and safely opens a Google Play Store URL.
 * Only accepts authoritative play.google.com URLs generated by the backend.
 */
export async function openGooglePlayStoreUrl(url: string): Promise<boolean> {
  const clean = (url || '').trim();

  if (!PLAY_STORE_URL_REGEX.test(clean)) {
    throw new Error(
      'Invalid Google Play Store link. Only official Play Store URLs are allowed.',
    );
  }

  const supported = await Linking.canOpenURL(clean);
  if (supported) {
    await Linking.openURL(clean);
    return true;
  } else {
    // Attempt open directly
    await Linking.openURL(clean);
    return true;
  }
}
